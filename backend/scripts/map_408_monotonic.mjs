// Interpolate any gaps
const fullMap = {};
for (let q = 1; q <= 408; q++) {
  if (anchors[q]) {
    fullMap[q] = anchors[q];
  } else {
    // Find closest anchor before and after
    let prevQ = q - 1;
    while (!anchors[prevQ] && prevQ > 1) prevQ--;
    let nextQ = q + 1;
    while (!anchors[nextQ] && nextQ < 408) nextQ++;
    
    const p1 = anchors[prevQ] || 1;
    const p2 = anchors[nextQ] || 211;
    const frac = (q - prevQ) / (nextQ - prevQ);
    fullMap[q] = Math.round(p1 + frac * (p2 - p1));
  }
}

