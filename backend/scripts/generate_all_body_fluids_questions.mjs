import fs from 'fs';

const pages = JSON.parse(fs.readFileSync('./backend/scripts/body_fluids_pages_dump.json', 'utf8'));
const officialKeys = JSON.parse(fs.readFileSync('./backend/scripts/body_fluids_official_keys.json', 'utf8'));
