import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

import { CE_PART1_OVERRIDES } from './clean_ce_part1.mjs';
import { CE_PART2_OVERRIDES } from './clean_ce_part2.mjs';
import { CE_PART3_OVERRIDES } from './clean_ce_part3.mjs';
import { CE_PART4_OVERRIDES } from './clean_ce_part4.mjs';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const officialKeys = JSON.parse(fs.readFileSync(path.resolve(__dirname, 'current_electricity_official_keys.json'), 'utf8'));
const diagUrls = JSON.parse(fs.readFileSync(path.resolve(__dirname, 'current_electricity_clean_diagram_urls.json'), 'utf8'));

const ALL_OVERRIDES = {
  ...CE_PART1_OVERRIDES,
  ...CE_PART2_OVERRIDES,
  ...CE_PART3_OVERRIDES,
  ...CE_PART4_OVERRIDES
};

async function buildMasterCurrentElectricity() {
  console.log('Building pristine 408 Current Electricity questions dataset...');
  
  const finalQuestions = [];
  const indexMap = { 'A': 0, 'B': 1, 'C': 2, 'D': 3 };

  for (let q = 1; q <= 408; q++) {
    const override = ALL_OVERRIDES[q];
    if (!override) {
      throw new Error(`Missing override for Question #${q}`);
    }

    const offKey = String(officialKeys[q] ?? '').trim();
    if (!offKey) {
      throw new Error(`Missing official key for Question #${q}`);
    }

    const isNumeric = !['A', 'B', 'C', 'D'].includes(offKey);
    const diagFile = `q${q}_question_diagram.png`;
    const image_url = diagUrls[diagFile] || null;

    let question_text = override.text.trim();
    let options = [];

    if (isNumeric) {
      options = [];
    } else {
      if (!override.options || override.options.length !== 4) {
        throw new Error(`Question #${q} is MCQ but has ${override.options ? override.options.length : 0} options!`);
      }
      options = override.options.map(opt => String(opt).trim());
    }

    const qItem = {
      q_num: q,
      question_text,
      options,
      question_type: isNumeric ? 'numerical' : 'mcq',
      numeric_answer: isNumeric ? (isNaN(Number(offKey)) ? offKey : Number(offKey)) : null,
      tolerance: isNumeric ? 0 : null,
      numerical_tolerance: isNumeric ? 0 : 0,
      correct_option: isNumeric ? null : offKey,
      correct_index: isNumeric ? null : (indexMap[offKey] ?? 0),
      correct_indices: isNumeric ? [] : [indexMap[offKey] ?? 0],
      marks: 4,
      negative_marks: isNumeric ? 0 : 1,
      hasDiagram: !!image_url,
      image_url,
      solution_image_url: null,
      solution: `Official Answer: ${offKey}`,
      difficulty: 'medium',
      topic: 'Current Electricity'
    };

    finalQuestions.push(qItem);
  }

  console.log(`Successfully compiled all ${finalQuestions.length} questions.`);

  // Write JSON
  const OUT_JSON = path.resolve(__dirname, 'current_electricity_jee_final_408.json');
  fs.writeFileSync(OUT_JSON, JSON.stringify(finalQuestions, null, 2), 'utf8');
  console.log(`Saved master JSON to: ${OUT_JSON}`);

  // Write MJS data module
  const OUT_MJS = path.resolve(__dirname, 'current_electricity_jee_questions_data.mjs');
  const mjsCode = `// Autogenerated 408 Pristine Current Electricity JEE Main PYQ Dataset\nexport const CURRENT_ELECTRICITY_JEE_QUESTIONS = ${JSON.stringify(finalQuestions, null, 2)};\n`;
  fs.writeFileSync(OUT_MJS, mjsCode, 'utf8');
  console.log(`Saved master MJS module to: ${OUT_MJS}`);
}

buildMasterCurrentElectricity().catch(err => {
  console.error('Build failed:', err);
  process.exit(1);
});
