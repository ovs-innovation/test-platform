export function getFilteredDronaAnalytics(testId = 'All', batchId = 'All') {
  let filtered = [...DRONA_STUDENTS];

  if (batchId && batchId !== 'All') {
    filtered = filtered.filter(
      (s) =>
        String(s.batch_id) === String(batchId) ||
        s.batch_name.toLowerCase() === String(batchId).toLowerCase()
    );
  }

  if (filtered.length === 0) {
    return DRONA_ANALYTICS;
  }

  const avg = Number(
    (filtered.reduce((sum, s) => sum + s.average_score, 0) / filtered.length).toFixed(1)
  );
  const highest = Math.max(...filtered.map((s) => s.average_score));

  const bioAvg = Number(
    (
      filtered.reduce((sum, s) => sum + ((s.biology_score || 300) / 360) * 100, 0) /
      filtered.length
    ).toFixed(1)
  );
  const chemAvg = Number(
    (
      filtered.reduce((sum, s) => sum + ((s.chemistry_score || 135) / 180) * 100, 0) /
      filtered.length
    ).toFixed(1)
  );
  const physAvg = Number(
    (
      filtered.reduce((sum, s) => sum + ((s.physics_score || 120) / 180) * 100, 0) /
      filtered.length
    ).toFixed(1)
  );

  return {
    average_score: avg,
    highest_score: highest,
    total_students: filtered.length,
    active_participating_students: filtered.length,
    total_attempts: filtered.length * 4,
    participation_rate: 100,
    batch_performance:
      batchId && batchId !== 'All'
        ? DRONA_ANALYTICS.batch_performance.filter(
            (b) =>
              b.batch_name.toLowerCase() === String(batchId).toLowerCase() ||
              (batchId === '101' && b.batch_name.includes('Achievers')) ||
              (batchId === '102' && b.batch_name.includes('Super 30'))
          )
        : DRONA_ANALYTICS.batch_performance,
    subject_performance: [
      {
        subject: 'Biology',
        score: bioAvg,
        avg_score: bioAvg,
        accuracy: Math.min(99, Number((bioAvg * 1.04).toFixed(1))),
        accuracy_rate: Math.min(99, Number((bioAvg * 1.04).toFixed(1))),
        tests_count: 4,
        tests: 4,
      },
      {
        subject: 'Chemistry',
        score: chemAvg,
        avg_score: chemAvg,
        accuracy: Math.min(99, Number((chemAvg * 1.05).toFixed(1))),
        accuracy_rate: Math.min(99, Number((chemAvg * 1.05).toFixed(1))),
        tests_count: 4,
        tests: 4,
      },
      {
        subject: 'Physics',
        score: physAvg,
        avg_score: physAvg,
        accuracy: Math.min(99, Number((physAvg * 1.06).toFixed(1))),
        accuracy_rate: Math.min(99, Number((physAvg * 1.06).toFixed(1))),
        tests_count: 4,
        tests: 4,
      },
    ],
  };
}

export function getFilteredDronaRankings(testId = 'All', batchId = 'All', search = '') {
  let list = [...DRONA_RANKINGS];

  if (batchId && batchId !== 'All') {
    list = list.filter(
      (r) =>
        String(r.batch_id) === String(batchId) ||
        r.batch_name.toLowerCase() === String(batchId).toLowerCase()
    );
  }

  if (search && search.trim()) {
    const q = search.toLowerCase();
    list = list.filter(
      (r) =>
        r.student_name.toLowerCase().includes(q) ||
        r.roll_number.toLowerCase().includes(q)
    );
  }

  // Recalculate rank position for the filtered view
  return list.map((item, idx) => ({
    ...item,
    institute_rank: idx + 1,
    rank: idx + 1,
  }));
}

