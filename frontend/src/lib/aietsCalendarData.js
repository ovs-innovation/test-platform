// Standard 1-Year 39 Schedule Default (NEET / Universal)
export const ONE_YEAR_39_SCHEDULE = NEET_CLASS_11_39_SCHEDULE;

export function getScheduleByProgram(programId) {
  if (!programId) return ONE_YEAR_39_SCHEDULE;
  const p = String(programId).toLowerCase();
  if (p.includes('jee') && (p.includes('repeater') || p.includes('rep') || p.includes('dropper') || p.includes('mul3gdpv'))) {
    return JEE_REPEATER_39_SCHEDULE;
  }
  if (p.includes('jee')) {
    return JEE_CLASS_12_39_SCHEDULE;
  }
  if (p.includes('11') || p.includes('neet-class-11')) {
    return NEET_CLASS_11_39_SCHEDULE;
  }
  return ONE_YEAR_39_SCHEDULE;
}
